"""Battery saves for movies that start from Continue.

A movie may declare, in a comment line:

    # from-save: save_academy

meaning "power on with the battery save that tools/movies/save_academy.movie
produces". The save is generated by playing that movie in the port (whose
saves match BizHawk byte for byte) and cached as build/saves/<name>.srm;
nothing derived from the game is committed.
"""
import os
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
HEADLESS = ROOT / "build" / ("native-Release/psiv_headless.exe" if os.name == "nt" else "native/psiv_headless")
SAVES = ROOT / "build" / "saves"
# saves no movie can make (the one a recorded session started from), kept by
# trace2movie.py; *.srm is git-ignored, so they stay local
FIXED = ROOT / "tools" / "movies" / "saves"


def last_frame(lines):
    prev = last = 0
    for line in lines:
        s = line.split("#")[0].split()
        if len(s) < 2:
            continue
        start = prev + int(s[0][1:]) if s[0].startswith("+") else int(s[0])
        n = int(s[2]) if len(s) > 2 else 1
        prev, last = start, max(last, start + n)
    return last


def save_for(movie: Path) -> Path | None:
    """The .srm a movie starts from (generating it if needed), or None."""
    for line in movie.read_text().splitlines():
        m = re.match(r"\s*#\s*from-save:\s*(\S+)", line)
        if m:
            return ensure_save(m.group(1))
    return None


def ensure_save(name: str) -> Path:
    out = SAVES / f"{name}.srm"
    src = ROOT / "tools" / "movies" / f"{name}.movie"
    if not src.exists():
        fixed = FIXED / f"{name}.srm"
        if fixed.exists():
            return fixed
        raise SystemExit(f"no save {fixed} and no movie {src} to make it")
    if out.exists() and out.stat().st_mtime >= src.stat().st_mtime:
        return out
    SAVES.mkdir(parents=True, exist_ok=True)
    parent = save_for(src)                         # saves can chain
    cmd = [str(HEADLESS), "--movie", str(src), "--frames", str(last_frame(src.read_text().splitlines()) + 60),
           "--sram-out", str(out)]
    if parent:
        cmd += ["--sram", str(parent)]
    subprocess.run(cmd, cwd=ROOT, check=True, capture_output=True)
    return out
