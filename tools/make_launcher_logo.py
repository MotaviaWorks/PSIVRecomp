#!/usr/bin/env python3
"""The launcher's logo (PsiLok's own artwork): res/launcher/logo.png -> runtime/launcher_logo.h.

  python tools/make_launcher_logo.py              the PNG as it is -> the header
  python tools/make_launcher_logo.py ARTWORK      first make the PNG from an export of the artwork
                                                  (any size, a transparent background): cut to what
                                                  is drawn, at most 1100 pixels wide

The header holds the PNG file's own bytes; the app reads them with SDL's PNG loader and scales the
picture to the window itself (main_sdl.c, logo_make), so nothing has to be shipped beside the program.
"""
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
PNG = ROOT / "res" / "launcher" / "logo.png"
OUT = ROOT / "runtime" / "launcher_logo.h"
MAX_W = 1100


def main():
    if len(sys.argv) > 1:
        art = Image.open(sys.argv[1]).convert("RGBA")
        box = art.getchannel("A").point(lambda a: 255 if a > 8 else 0).getbbox()
        if not box:
            sys.exit("nothing is drawn in that picture (is its background transparent?)")
        art = art.crop(box)
        if art.width > MAX_W:
            # scaled with the colours weighted by their alpha, so edges keep no dark fringe
            art = art.convert("RGBa").resize((MAX_W, round(art.height * MAX_W / art.width)), Image.LANCZOS).convert("RGBA")
        PNG.parent.mkdir(parents=True, exist_ok=True)
        art.save(PNG, optimize=True)
    data = PNG.read_bytes()
    w, h = Image.open(PNG).size
    lines = ["/* Generated by tools/make_launcher_logo.py from res/launcher/logo.png (PsiLok's artwork):",
             f" * the PNG file's bytes, {w} x {h}. The launcher reads them with SDL's PNG loader. */",
             f"static const unsigned char LAUNCHER_LOGO_PNG[{len(data)}] = {{"]
    for i in range(0, len(data), 32):
        lines.append(",".join(str(b) for b in data[i:i + 32]) + ",")
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n", encoding="ascii", newline="\n")
    print(f"{PNG.relative_to(ROOT)}: {w}x{h}, {len(data) // 1024} KB -> {OUT.relative_to(ROOT)} ({OUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
